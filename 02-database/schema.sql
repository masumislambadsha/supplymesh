-- =====================================================================
-- SupplyMesh — Reference PostgreSQL 16 schema
-- ---------------------------------------------------------------------
-- This file is the single source of truth for table names, columns,
-- enums and constraints used across the documentation.
-- In the real application this would be generated/managed by Drizzle
-- migrations; it is written as plain SQL here so it can be reviewed
-- and loaded into any PostgreSQL 16 instance for verification.
--
-- Conventions
--   * Every tenant-owned table carries organization_id NOT NULL.
--   * Every tenant-owned table that other tables point to exposes UNIQUE (organization_id, id) so
--     child tables can use COMPOSITE foreign keys
--     (organization_id, parent_id) -> parent(organization_id, id).
--     This makes cross-tenant references impossible at the DB level.
--   * Money: NUMERIC(19,4) + ISO-4217 currency code. Never float.
--   * Quantities: NUMERIC(14,3).
--   * IDs: UUID (v7 generated by the app for index locality;
--     gen_random_uuid() default kept as a fallback).
--   * Optimistic locking: "version" INT on rows that are edited
--     concurrently (purchase requests, POs, invoices, suppliers).
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS pg_trgm;   -- fuzzy supplier-name search

-- ---------------------------------------------------------------------
-- Enums
-- ---------------------------------------------------------------------
CREATE TYPE org_status            AS ENUM ('trial','active','suspended','closed');
CREATE TYPE user_status           AS ENUM ('active','disabled');
CREATE TYPE member_status         AS ENUM ('invited','active','deactivated');
CREATE TYPE supplier_status       AS ENUM ('draft','pending_verification','active','suspended','blacklisted','rejected');
CREATE TYPE risk_level            AS ENUM ('low','medium','high','critical');
CREATE TYPE supplier_doc_type     AS ENUM ('trade_license','tax_certificate','bank_letter','iso_certificate','insurance','nda','contract','other');
CREATE TYPE supplier_doc_status   AS ENUM ('pending','approved','rejected','expired');
CREATE TYPE request_priority      AS ENUM ('low','medium','high','urgent');
CREATE TYPE purchase_request_status AS ENUM ('draft','submitted','in_approval','approved','rejected','returned','cancelled','converted');
CREATE TYPE workflow_version_status AS ENUM ('draft','published','retired');
CREATE TYPE approver_type         AS ENUM ('role','department_manager','specific_member');
CREATE TYPE approval_step_status  AS ENUM ('waiting','pending','approved','rejected','skipped');
CREATE TYPE approval_decision_type AS ENUM ('approved','rejected','returned');
CREATE TYPE purchase_order_status AS ENUM ('draft','issued','acknowledged','partially_received','received','closed','cancelled');
CREATE TYPE invoice_status        AS ENUM ('received','matched','discrepancy','approved','partially_paid','paid','rejected','void');
CREATE TYPE discrepancy_type      AS ENUM ('price','quantity','tax','total','missing_receipt','currency');
CREATE TYPE discrepancy_status    AS ENUM ('open','accepted','rejected','resolved');
CREATE TYPE payment_method        AS ENUM ('bank_transfer','cheque','card','other');
CREATE TYPE payment_status        AS ENUM ('scheduled','processing','completed','failed','cancelled');

-- =====================================================================
-- 1. Identity & tenancy
-- =====================================================================

-- Global identity: one person = one user row, can belong to many orgs.
CREATE TABLE users (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email           CITEXT NOT NULL UNIQUE,
  full_name       VARCHAR(150) NOT NULL,
  password_hash   TEXT,                       -- NULL when SSO-only
  mfa_secret_enc  TEXT,                       -- encrypted TOTP secret
  status          user_status NOT NULL DEFAULT 'active',
  last_login_at   TIMESTAMPTZ,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE user_sessions (
  id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id            UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  refresh_token_hash TEXT NOT NULL UNIQUE,
  ip_address         INET,
  user_agent         TEXT,
  expires_at         TIMESTAMPTZ NOT NULL,
  revoked_at         TIMESTAMPTZ,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_user_sessions_user ON user_sessions(user_id) WHERE revoked_at IS NULL;

CREATE TABLE organizations (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name            VARCHAR(200) NOT NULL,
  slug            VARCHAR(80)  NOT NULL UNIQUE,
  base_currency   CHAR(3) NOT NULL DEFAULT 'USD',
  country_code    CHAR(2),
  timezone        VARCHAR(64) NOT NULL DEFAULT 'UTC',
  status          org_status NOT NULL DEFAULT 'trial',
  settings        JSONB NOT NULL DEFAULT '{}'::jsonb,  -- e.g. invoice match tolerances
  owner_user_id   UUID NOT NULL REFERENCES users(id),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_org_currency CHECK (base_currency ~ '^[A-Z]{3}$')
);

CREATE TABLE departments (
  id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id       UUID NOT NULL REFERENCES organizations(id),
  name                  VARCHAR(120) NOT NULL,
  code                  VARCHAR(20)  NOT NULL,
  parent_department_id  UUID,
  manager_member_id     UUID,   -- FK added after organization_members exists
  cost_center           VARCHAR(40),
  is_active             BOOLEAN NOT NULL DEFAULT true,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (organization_id, id),
  UNIQUE (organization_id, code),
  FOREIGN KEY (organization_id, parent_department_id) REFERENCES departments(organization_id, id)
);

-- Membership of a user inside an organization (the tenant-scoped "person").
CREATE TABLE organization_members (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id UUID NOT NULL REFERENCES organizations(id),
  user_id         UUID NOT NULL REFERENCES users(id),
  department_id   UUID,
  job_title       VARCHAR(120),
  status          member_status NOT NULL DEFAULT 'invited',
  joined_at       TIMESTAMPTZ,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (organization_id, id),
  UNIQUE (organization_id, user_id),
  FOREIGN KEY (organization_id, department_id) REFERENCES departments(organization_id, id)
);
CREATE INDEX idx_members_user ON organization_members(user_id);

ALTER TABLE departments
  ADD CONSTRAINT fk_departments_manager
  FOREIGN KEY (organization_id, manager_member_id) REFERENCES organization_members(organization_id, id);

CREATE TABLE invitations (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id UUID NOT NULL REFERENCES organizations(id),
  email           CITEXT NOT NULL,
  role_id         UUID NOT NULL,
  department_id   UUID,
  token_hash      TEXT NOT NULL UNIQUE,
  invited_by_member_id UUID NOT NULL,
  expires_at      TIMESTAMPTZ NOT NULL,
  accepted_at     TIMESTAMPTZ,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (organization_id, id),
  FOREIGN KEY (organization_id, department_id)        REFERENCES departments(organization_id, id),
  FOREIGN KEY (organization_id, invited_by_member_id) REFERENCES organization_members(organization_id, id)
);
-- Only one open invitation per email per org
CREATE UNIQUE INDEX uq_open_invitation ON invitations(organization_id, email) WHERE accepted_at IS NULL;

-- =====================================================================
-- 2. RBAC
-- =====================================================================

-- Global permission catalog, owned by the platform (not by a tenant).
CREATE TABLE permissions (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code        VARCHAR(80) NOT NULL UNIQUE,   -- e.g. 'purchase_request.approve'
  module      VARCHAR(40) NOT NULL,          -- e.g. 'procurement'
  description TEXT NOT NULL
);

-- Roles are per-organization. System roles (Owner, Procurement Manager,
-- Department Manager, Finance Officer, Employee) are seeded for each org
-- with is_system = true and cannot be deleted; orgs may add custom roles.
CREATE TABLE roles (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id UUID NOT NULL REFERENCES organizations(id),
  name            VARCHAR(80) NOT NULL,
  key             VARCHAR(40) NOT NULL,      -- e.g. 'procurement_manager'
  description     TEXT,
  is_system       BOOLEAN NOT NULL DEFAULT false,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (organization_id, id),
  UNIQUE (organization_id, key)
);

CREATE TABLE role_permissions (
  organization_id UUID NOT NULL,
  role_id         UUID NOT NULL,
  permission_id   UUID NOT NULL REFERENCES permissions(id),
  PRIMARY KEY (role_id, permission_id),
  FOREIGN KEY (organization_id, role_id) REFERENCES roles(organization_id, id) ON DELETE CASCADE
);

-- A member can hold several roles; a role can be scoped to one department
-- (e.g. Department Manager of "IT") and carry a monetary approval limit.
CREATE TABLE member_roles (
  id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id       UUID NOT NULL,
  member_id             UUID NOT NULL,
  role_id               UUID NOT NULL,
  scope_department_id   UUID,                        -- NULL = organization-wide
  approval_limit_amount NUMERIC(19,4),               -- in org base currency; NULL = no personal cap (the workflow rule decides)
  granted_by_member_id  UUID,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  FOREIGN KEY (organization_id, member_id)            REFERENCES organization_members(organization_id, id) ON DELETE CASCADE,
  FOREIGN KEY (organization_id, role_id)              REFERENCES roles(organization_id, id),
  FOREIGN KEY (organization_id, scope_department_id)  REFERENCES departments(organization_id, id),
  FOREIGN KEY (organization_id, granted_by_member_id) REFERENCES organization_members(organization_id, id),
  CONSTRAINT chk_limit_positive CHECK (approval_limit_amount IS NULL OR approval_limit_amount >= 0)
);
CREATE UNIQUE INDEX uq_member_role_scope
  ON member_roles(member_id, role_id, COALESCE(scope_department_id, '00000000-0000-0000-0000-000000000000'::uuid));
CREATE INDEX idx_member_roles_org_role ON member_roles(organization_id, role_id);

ALTER TABLE invitations
  ADD CONSTRAINT fk_invitations_role FOREIGN KEY (organization_id, role_id) REFERENCES roles(organization_id, id);

-- Gap-free, per-organization document numbers (PR-2026-000123, PO-..., GRN-...)
CREATE TABLE organization_sequences (
  organization_id UUID NOT NULL REFERENCES organizations(id),
  sequence_key    VARCHAR(20) NOT NULL,   -- 'SUP', 'PR', 'PO', 'GRN', 'PAY'
  next_value      BIGINT NOT NULL DEFAULT 1,
  PRIMARY KEY (organization_id, sequence_key)
);

-- =====================================================================
-- 3. Supplier management
-- =====================================================================

CREATE TABLE supplier_categories (
  id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id    UUID NOT NULL REFERENCES organizations(id),
  name               VARCHAR(120) NOT NULL,
  parent_category_id UUID,
  UNIQUE (organization_id, id),
  UNIQUE (organization_id, name),
  FOREIGN KEY (organization_id, parent_category_id) REFERENCES supplier_categories(organization_id, id)
);

CREATE TABLE suppliers (
  id                   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id      UUID NOT NULL REFERENCES organizations(id),
  supplier_code        VARCHAR(30) NOT NULL,
  legal_name           VARCHAR(200) NOT NULL,
  trade_name           VARCHAR(200),
  registration_number  VARCHAR(80),
  tax_id               VARCHAR(80),
  country_code         CHAR(2) NOT NULL,
  category_id          UUID,
  default_currency     CHAR(3) NOT NULL,
  payment_terms_days   SMALLINT NOT NULL DEFAULT 30,
  contact_name         VARCHAR(150),
  contact_email        CITEXT,
  contact_phone        VARCHAR(40),
  address              JSONB,
  bank_details_enc     TEXT,                    -- encrypted at application level
  status               supplier_status NOT NULL DEFAULT 'draft',
  risk_level           risk_level NOT NULL DEFAULT 'medium',
  status_reason        TEXT,
  onboarding_token_hash TEXT UNIQUE,            -- one-time link for supplier self-registration
  onboarding_token_expires_at TIMESTAMPTZ,
  verified_by_member_id UUID,
  verified_at          TIMESTAMPTZ,
  created_by_member_id UUID,
  bank_details_changed_by_member_id UUID,     -- BR-05: this member cannot be the one who re-verifies
  version              INT NOT NULL DEFAULT 1,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at           TIMESTAMPTZ,             -- soft delete: suppliers are referenced by financial history
  UNIQUE (organization_id, id),
  UNIQUE (organization_id, supplier_code),
  FOREIGN KEY (organization_id, category_id)           REFERENCES supplier_categories(organization_id, id),
  FOREIGN KEY (organization_id, verified_by_member_id) REFERENCES organization_members(organization_id, id),
  FOREIGN KEY (organization_id, created_by_member_id)  REFERENCES organization_members(organization_id, id),
  FOREIGN KEY (organization_id, bank_details_changed_by_member_id) REFERENCES organization_members(organization_id, id),
  CONSTRAINT chk_supplier_verified CHECK (status <> 'active' OR verified_at IS NOT NULL)
);
-- The same legal entity cannot be registered twice in one org
CREATE UNIQUE INDEX uq_supplier_tax_id ON suppliers(organization_id, country_code, tax_id)
  WHERE tax_id IS NOT NULL AND deleted_at IS NULL;
CREATE INDEX idx_suppliers_org_status ON suppliers(organization_id, status) WHERE deleted_at IS NULL;
CREATE INDEX idx_suppliers_name_trgm  ON suppliers USING gin (legal_name gin_trgm_ops);

CREATE TABLE supplier_documents (
  id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id       UUID NOT NULL,
  supplier_id           UUID NOT NULL,
  document_type         supplier_doc_type NOT NULL,
  file_key              TEXT NOT NULL,          -- S3 object key, never a public URL
  file_name             VARCHAR(255) NOT NULL,
  mime_type             VARCHAR(100) NOT NULL,
  size_bytes            BIGINT NOT NULL,
  checksum_sha256       CHAR(64) NOT NULL,
  issued_at             DATE,
  expires_at            DATE,
  status                supplier_doc_status NOT NULL DEFAULT 'pending',
  review_note           TEXT,
  uploaded_by_member_id UUID,                   -- NULL when uploaded by the supplier via onboarding link
  reviewed_by_member_id UUID,
  reviewed_at           TIMESTAMPTZ,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (organization_id, id),
  FOREIGN KEY (organization_id, supplier_id)           REFERENCES suppliers(organization_id, id),
  FOREIGN KEY (organization_id, uploaded_by_member_id) REFERENCES organization_members(organization_id, id),
  FOREIGN KEY (organization_id, reviewed_by_member_id) REFERENCES organization_members(organization_id, id),
  CONSTRAINT chk_doc_size CHECK (size_bytes > 0 AND size_bytes <= 26214400),  -- 25 MB
  CONSTRAINT chk_doc_dates CHECK (expires_at IS NULL OR issued_at IS NULL OR expires_at > issued_at)
);
CREATE INDEX idx_supplier_docs_supplier ON supplier_documents(organization_id, supplier_id);
CREATE INDEX idx_supplier_docs_expiry   ON supplier_documents(expires_at) WHERE status = 'approved';

-- =====================================================================
-- 4. Approval workflow DEFINITIONS (configurable per organization)
-- =====================================================================

CREATE TABLE approval_workflows (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id UUID NOT NULL REFERENCES organizations(id),
  name            VARCHAR(120) NOT NULL,
  subject_type    VARCHAR(40) NOT NULL DEFAULT 'purchase_request',
  is_active       BOOLEAN NOT NULL DEFAULT true,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (organization_id, id),
  UNIQUE (organization_id, name)
);
-- Only one active workflow per subject type per org
CREATE UNIQUE INDEX uq_active_workflow ON approval_workflows(organization_id, subject_type) WHERE is_active;

-- Versions are immutable once published. Requests point at the version
-- that was live when they were submitted, so editing a policy never
-- changes requests already in flight.
CREATE TABLE approval_workflow_versions (
  id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id        UUID NOT NULL,
  workflow_id            UUID NOT NULL,
  version_no             INT NOT NULL,
  status                 workflow_version_status NOT NULL DEFAULT 'draft',
  published_at           TIMESTAMPTZ,
  published_by_member_id UUID,
  created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (organization_id, id),
  UNIQUE (workflow_id, version_no),
  FOREIGN KEY (organization_id, workflow_id)            REFERENCES approval_workflows(organization_id, id),
  FOREIGN KEY (organization_id, published_by_member_id) REFERENCES organization_members(organization_id, id)
);
CREATE UNIQUE INDEX uq_one_published_version ON approval_workflow_versions(workflow_id) WHERE status = 'published';

-- A rule decides WHICH chain of steps applies to a request.
-- Rules are evaluated by ascending priority; first match wins.
CREATE TABLE approval_rules (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id     UUID NOT NULL,
  workflow_version_id UUID NOT NULL,
  name                VARCHAR(120) NOT NULL,
  priority            INT NOT NULL,
  min_amount          NUMERIC(19,4) NOT NULL DEFAULT 0,   -- inclusive, base currency
  max_amount          NUMERIC(19,4),                      -- exclusive; NULL = no upper bound
  department_id       UUID,                               -- NULL = any department
  category_id         UUID,                               -- NULL = any category
  min_priority        request_priority,                   -- NULL = any priority
  UNIQUE (organization_id, id),
  UNIQUE (workflow_version_id, priority),
  FOREIGN KEY (organization_id, workflow_version_id) REFERENCES approval_workflow_versions(organization_id, id) ON DELETE CASCADE,
  FOREIGN KEY (organization_id, department_id)       REFERENCES departments(organization_id, id),
  FOREIGN KEY (organization_id, category_id)         REFERENCES supplier_categories(organization_id, id),
  CONSTRAINT chk_rule_range CHECK (max_amount IS NULL OR max_amount > min_amount)
);

-- Steps of a rule. Same step_order = parallel; increasing = sequential.
CREATE TABLE approval_step_templates (
  id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id    UUID NOT NULL,
  rule_id            UUID NOT NULL,
  step_order         SMALLINT NOT NULL,
  name               VARCHAR(120) NOT NULL,
  approver_type      approver_type NOT NULL,
  approver_role_id   UUID,
  approver_member_id UUID,
  required_approvals SMALLINT NOT NULL DEFAULT 1,      -- quorum (e.g. 2 of N finance officers)
  sla_hours          SMALLINT,                         -- escalation threshold
  UNIQUE (organization_id, id),
  FOREIGN KEY (organization_id, rule_id)            REFERENCES approval_rules(organization_id, id) ON DELETE CASCADE,
  FOREIGN KEY (organization_id, approver_role_id)   REFERENCES roles(organization_id, id),
  FOREIGN KEY (organization_id, approver_member_id) REFERENCES organization_members(organization_id, id),
  CONSTRAINT chk_step_order    CHECK (step_order >= 1),
  CONSTRAINT chk_required      CHECK (required_approvals >= 1),
  CONSTRAINT chk_approver_target CHECK (
       (approver_type = 'role'               AND approver_role_id IS NOT NULL AND approver_member_id IS NULL)
    OR (approver_type = 'specific_member'    AND approver_member_id IS NOT NULL AND approver_role_id IS NULL)
    OR (approver_type = 'department_manager' AND approver_role_id IS NULL AND approver_member_id IS NULL))
);

-- =====================================================================
-- 5. Purchase requests + approval RUNTIME
-- =====================================================================

CREATE TABLE purchase_requests (
  id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id        UUID NOT NULL,
  request_number         VARCHAR(30) NOT NULL,
  requester_member_id    UUID NOT NULL,
  department_id          UUID NOT NULL,
  category_id            UUID,
  title                  VARCHAR(200) NOT NULL,
  description            TEXT,
  priority               request_priority NOT NULL DEFAULT 'medium',
  required_by_date       DATE NOT NULL,
  currency               CHAR(3) NOT NULL,
  estimated_total        NUMERIC(19,4) NOT NULL DEFAULT 0,
  estimated_total_base   NUMERIC(19,4) NOT NULL DEFAULT 0,   -- converted at submission; used by rules & analytics
  fx_rate_to_base        NUMERIC(18,8) NOT NULL DEFAULT 1,
  status                 purchase_request_status NOT NULL DEFAULT 'draft',
  workflow_version_id    UUID,                               -- snapshot at submission
  matched_rule_id        UUID,
  submitted_at           TIMESTAMPTZ,
  decided_at             TIMESTAMPTZ,
  version                INT NOT NULL DEFAULT 1,
  created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (organization_id, id),
  UNIQUE (organization_id, request_number),
  FOREIGN KEY (organization_id, requester_member_id) REFERENCES organization_members(organization_id, id),
  FOREIGN KEY (organization_id, department_id)       REFERENCES departments(organization_id, id),
  FOREIGN KEY (organization_id, category_id)         REFERENCES supplier_categories(organization_id, id),
  FOREIGN KEY (organization_id, workflow_version_id) REFERENCES approval_workflow_versions(organization_id, id),
  FOREIGN KEY (organization_id, matched_rule_id)     REFERENCES approval_rules(organization_id, id),
  CONSTRAINT chk_pr_total CHECK (estimated_total >= 0),
  -- a draft can be cancelled without ever being submitted
  CONSTRAINT chk_pr_submitted CHECK (status IN ('draft','cancelled') OR submitted_at IS NOT NULL)
);
CREATE INDEX idx_pr_org_status       ON purchase_requests(organization_id, status, created_at DESC);
CREATE INDEX idx_pr_org_dept_created ON purchase_requests(organization_id, department_id, created_at DESC);
CREATE INDEX idx_pr_requester        ON purchase_requests(organization_id, requester_member_id, created_at DESC);
CREATE INDEX idx_pr_pending          ON purchase_requests(organization_id, submitted_at)
  WHERE status IN ('submitted','in_approval');

CREATE TABLE purchase_request_items (
  id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id       UUID NOT NULL,
  purchase_request_id   UUID NOT NULL,
  line_no               SMALLINT NOT NULL,
  item_name             VARCHAR(200) NOT NULL,
  description           TEXT,
  quantity              NUMERIC(14,3) NOT NULL,
  unit_of_measure       VARCHAR(20) NOT NULL DEFAULT 'unit',
  estimated_unit_price  NUMERIC(19,4) NOT NULL,
  line_total            NUMERIC(19,4) GENERATED ALWAYS AS (quantity * estimated_unit_price) STORED,
  preferred_supplier_id UUID,
  UNIQUE (organization_id, id),
  UNIQUE (purchase_request_id, line_no),
  FOREIGN KEY (organization_id, purchase_request_id)   REFERENCES purchase_requests(organization_id, id) ON DELETE CASCADE,
  FOREIGN KEY (organization_id, preferred_supplier_id) REFERENCES suppliers(organization_id, id),
  CONSTRAINT chk_pri_qty   CHECK (quantity > 0),
  CONSTRAINT chk_pri_price CHECK (estimated_unit_price >= 0)
);

-- Discussion thread on a request between the requester and procurement (PR-06).
-- Append-only: comments are never edited or deleted.
CREATE TABLE purchase_request_comments (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id     UUID NOT NULL,
  purchase_request_id UUID NOT NULL,
  author_member_id    UUID NOT NULL,
  body                TEXT NOT NULL,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  FOREIGN KEY (organization_id, purchase_request_id) REFERENCES purchase_requests(organization_id, id),
  FOREIGN KEY (organization_id, author_member_id)    REFERENCES organization_members(organization_id, id),
  CONSTRAINT chk_prc_body CHECK (length(btrim(body)) > 0)
);
CREATE INDEX idx_prc_request ON purchase_request_comments(organization_id, purchase_request_id, created_at);

-- One row per step instance created from the matched rule at submission.
CREATE TABLE approval_steps (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id     UUID NOT NULL,
  purchase_request_id UUID NOT NULL,
  step_template_id    UUID,             -- NULL = step added by the engine (escalation or reroute), not copied from a template
  round               SMALLINT NOT NULL DEFAULT 1,   -- +1 on each resubmission; only the current round is live
  step_order          SMALLINT NOT NULL,
  name                VARCHAR(120) NOT NULL,
  approver_type       approver_type NOT NULL,
  approver_role_id    UUID,
  approver_member_id  UUID,             -- resolved person for department_manager / specific_member
  required_approvals  SMALLINT NOT NULL,
  approvals_count     SMALLINT NOT NULL DEFAULT 0,
  status              approval_step_status NOT NULL DEFAULT 'waiting',
  activated_at        TIMESTAMPTZ,
  due_at              TIMESTAMPTZ,
  completed_at        TIMESTAMPTZ,
  UNIQUE (organization_id, id),
  FOREIGN KEY (organization_id, purchase_request_id) REFERENCES purchase_requests(organization_id, id),
  FOREIGN KEY (organization_id, step_template_id)    REFERENCES approval_step_templates(organization_id, id),
  FOREIGN KEY (organization_id, approver_role_id)    REFERENCES roles(organization_id, id),
  FOREIGN KEY (organization_id, approver_member_id)  REFERENCES organization_members(organization_id, id),
  CONSTRAINT chk_approvals_count CHECK (approvals_count >= 0 AND approvals_count <= required_approvals)
);
CREATE INDEX idx_steps_request ON approval_steps(organization_id, purchase_request_id, step_order);
-- "My approval inbox" queries
CREATE INDEX idx_steps_pending_member ON approval_steps(organization_id, approver_member_id) WHERE status = 'pending';
CREATE INDEX idx_steps_pending_role   ON approval_steps(organization_id, approver_role_id)   WHERE status = 'pending';
CREATE INDEX idx_steps_overdue        ON approval_steps(due_at) WHERE status = 'pending';

CREATE TABLE approval_decisions (
  id                   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id      UUID NOT NULL,
  approval_step_id     UUID NOT NULL,
  decided_by_member_id UUID NOT NULL,
  decision             approval_decision_type NOT NULL,
  comment              TEXT,
  decided_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (organization_id, id),
  UNIQUE (approval_step_id, decided_by_member_id),   -- one vote per person per step
  FOREIGN KEY (organization_id, approval_step_id)     REFERENCES approval_steps(organization_id, id),
