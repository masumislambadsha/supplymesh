-- =====================================================================
-- 10. Row-Level Security (defence in depth for multi-tenancy)
-- ---------------------------------------------------------------------
-- The API sets `SET LOCAL app.current_org_id = '<uuid>'` at the start of
-- every request transaction. Even if a repository forgets a WHERE
-- organization_id = ..., PostgreSQL will not return other tenants' rows.
--
-- NULLIF(..., '') makes an unset tenant compare to NULL -> no rows
-- (fail closed) instead of a uuid cast error on pooled connections where
-- the setting has reverted to ''.
--
-- Pre-tenant lookups (the org is not known yet):
--   * Login / org switcher: policy `member_self_lookup` below lets a
--     user SELECT only their own memberships, keyed on app.current_user_id
--     (set from the verified session, never from client input).
--   * Invitation accept and supplier onboarding links: tokens have the
--     form "<organization_id>.<secret>". The API sets app.current_org_id
--     from the prefix, then matches the SHA-256 of the secret inside that
--     tenant. A forged prefix simply finds no row.
-- =====================================================================
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'departments','organization_members','invitations','roles','role_permissions','member_roles',
    'organization_sequences','supplier_categories','suppliers','supplier_documents',
    'approval_workflows','approval_workflow_versions','approval_rules','approval_step_templates',
    'purchase_requests','purchase_request_items','purchase_request_comments','approval_steps','approval_decisions',
    'purchase_orders','purchase_order_items','goods_receipts','goods_receipt_items',
    'invoices','invoice_items','invoice_discrepancies','payments',
    'supplier_performance_records','audit_logs','notifications','outbox_events'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON %I '
      'USING (organization_id = NULLIF(current_setting(''app.current_org_id'', true), '''')::uuid) '
      'WITH CHECK (organization_id = NULLIF(current_setting(''app.current_org_id'', true), '''')::uuid)', t);
  END LOOP;
END $$;

-- Permissive policies are OR-ed: in addition to tenant_isolation, a user may
-- read (never write) their own membership rows across organizations.
CREATE POLICY member_self_lookup ON organization_members FOR SELECT
  USING (user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid);


-- The tenant table itself. A session sees only its own organization row.
-- Sign-up sets app.current_org_id to the new organization's id before inserting it.
ALTER TABLE organizations ENABLE ROW LEVEL SECURITY;
ALTER TABLE organizations FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON organizations
  USING (id = NULLIF(current_setting('app.current_org_id', true), '')::uuid)
  WITH CHECK (id = NULLIF(current_setting('app.current_org_id', true), '')::uuid);
-- Login / organization switcher: a user may read (never write) the organizations they belong to.
CREATE POLICY org_member_lookup ON organizations FOR SELECT
  USING (id IN (SELECT organization_id FROM organization_members
                WHERE user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid));

-- users, user_sessions and permissions are global on purpose (no RLS): a person exists
-- before any organization is chosen, and permissions is a read-only platform catalog.

